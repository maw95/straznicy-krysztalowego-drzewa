// Collects the results of scripts/sim/tuneLevels.ts (.tmp/sim/auto-*.json) into src/engine/tuningAuto.ts, which DIGITAL_TUNING appends last.
// Usage: node --import tsx scripts/sim/tuneMerge.ts

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const files = readdirSync('.tmp/sim').filter((f) => /^auto-.*\.json$/.test(f)).sort();
// One JSON entry per line, inside a string: a 1300-element literal of differently shaped objects is too much for the type checker.
const lines: string[] = [];
let count = 0;
for (const f of files) {
  const { games, entries } = JSON.parse(readFileSync(`.tmp/sim/${f}`, 'utf8')) as { games: number; entries: Array<Record<string, unknown>> };
  lines.push(`# ${f.replace(/^auto-|\.json$/g, '')} (${entries.length} cells, ${games} games each)`);
  for (const e of entries) (lines.push(JSON.stringify(e)), count++);
}
writeFileSync(
  'src/engine/tuningAuto.ts',
  `// Generated by scripts/sim/tuneLevels.ts and scripts/sim/tuneMerge.ts (do not edit by hand; run the tuner again instead).
// One entry per map size, table and level, for every map shape, goal and hero growth setting the tuner went through (lines starting
// with # are comments). They come last in DIGITAL_TUNING and win over the older, hand-made entries. Targets (the author, 9.11.2026):
// wins of the Przymierza Easy 65-85 percent, Normal 45-65, Hard 30-45.

import type { DigitalTune } from './tuning';

const ENTRIES = \`
${lines.join('\n')}
\`;

export const AUTO_TUNING: DigitalTune[] = ENTRIES.split('\\n')
  .filter((l) => l.startsWith('{'))
  .map((l) => JSON.parse(l) as DigitalTune);
`,
);
console.log(`${files.length} files, ${count} entries`);
