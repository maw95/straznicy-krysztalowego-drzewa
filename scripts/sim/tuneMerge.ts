// Collects the results of scripts/sim/tuneLevels.ts (.tmp/sim/auto-*.json) into src/engine/tuningAuto.ts, which DIGITAL_TUNING appends last.
// Usage: node --import tsx scripts/sim/tuneMerge.ts

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const files = readdirSync('.tmp/sim').filter((f) => /^auto-.*\.json$/.test(f)).sort();
const lines: string[] = [];
for (const f of files) {
  const { objective, growth, games, entries } = JSON.parse(readFileSync(`.tmp/sim/${f}`, 'utf8')) as { objective: string; growth: boolean; games: number; entries: Array<Record<string, unknown>> };
  lines.push(`  // ${objective}, hero growth ${growth ? 'on' : 'off'} (${entries.length} cells, ${games} games each)`);
  for (const e of entries) lines.push(`  ${JSON.stringify(e).replace(/"([a-zA-Z]+)":/g, '$1:').replace(/"/g, "'")},`);
}
writeFileSync(
  'src/engine/tuningAuto.ts',
  `// Generated by scripts/sim/tuneLevels.ts and scripts/sim/tuneMerge.ts (do not edit by hand; run the tuner again instead).
// One entry per map size, table and level on the triangle map, for the goals and growth settings the tuner went through. They come last
// in DIGITAL_TUNING and win over the older, hand-made entries. Targets (the author, 9.11.2026): wins of the Przymierza
// Easy 60-80 percent, Normal 40-60, Hard 30-45.

import type { DigitalTune } from './tuning';

export const AUTO_TUNING: DigitalTune[] = [
${lines.join('\n')}
];
`,
);
console.log(`${files.length} files, ${lines.filter((l) => !l.startsWith('  //')).length} entries`);
